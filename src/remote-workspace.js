import { createHash, randomUUID } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, join, resolve } from 'node:path';
import { shellQuote } from './util.js';

export const REMOTE_PRESET_ID = 'openssh-remote';
export const REMOTE_MANIFEST = '.dsh-openssh-workspace.json';

function dshHome() {
  return process.env.DSH_HOME || join(homedir(), '.dsh');
}

function remoteWorkspaceRoot() {
  return join(dshHome(), 'remote-workspaces');
}

function presetRoot() {
  return join(dshHome(), '.agent-presets', REMOTE_PRESET_ID);
}

function safeAlias(value) {
  const alias = String(value || '').trim();
  if (!alias || alias.startsWith('-') || /[\s\\/\0]/u.test(alias)) throw new Error('invalid SSH alias');
  return alias;
}

function normalizeRemotePath(value) {
  let path = String(value || '').trim().replace(/\/+$/u, '');
  if (path === '') path = '/';
  if (!path.startsWith('/') || /[\r\n\0]/u.test(path)) {
    throw new Error('remote workspace path must be an absolute POSIX path');
  }
  return path;
}

function anchorFor(alias, remotePath) {
  const safe = alias.replace(/[^A-Za-z0-9_.-]+/gu, '_');
  const digest = createHash('sha256').update(`${alias}\0${remotePath}`).digest('hex').slice(0, 16);
  return join(remoteWorkspaceRoot(), safe, digest);
}

function displayTitle(alias, remotePath) {
  const clean = remotePath === '/' ? 'root' : basename(remotePath.replace(/\/+$/u, '')) || 'remote';
  return `${clean} · ${alias}`;
}

function manifestAt(anchor) {
  return join(anchor, REMOTE_MANIFEST);
}

export function readRemoteWorkspaceManifest(anchor) {
  try {
    const parsed = JSON.parse(readFileSync(manifestAt(anchor), 'utf8'));
    if (parsed?.version !== 1) return undefined;
    return {
      version: 1,
      alias: safeAlias(parsed.alias),
      remotePath: normalizeRemotePath(parsed.remotePath),
      title: String(parsed.title || displayTitle(parsed.alias, parsed.remotePath)),
      anchor: resolve(anchor),
    };
  } catch {
    return undefined;
  }
}

function writeRemoteWorkspaceManifest(anchor, value) {
  mkdirSync(anchor, { recursive: true });
  writeFileSync(manifestAt(anchor), `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

const PRESET_CORDIS = `# Generated by dsh-openssh-vpn. This preset intentionally does not mount
# the host-local filesystem or PowerShell tools: the workspace cwd is only a
# local Harness anchor while all project I/O is executed on the mapped SSH host.
- id: persona
  name: '@deepseek-ai/dsh-persona'
  config:
    text: >-
      You are a coding agent working in an SSH-backed remote workspace. The local
      session cwd is only a Harness workspace anchor. Use bash/read/write/edit/glob/grep
      for project work; those tools operate on the mapped remote host and directory.
      Never treat the Windows anchor directory as the project contents.

- id: openssh-remote-tools
  name: 'dsh-openssh-vpn/remote-tools'

- id: tool-todo
  name: '@deepseek-ai/dsh-tool-todo'
  config:
    allowParallelInProgress: true

- id: tool-ask-user
  name: '@deepseek-ai/dsh-tool-ask-user'

- id: tool-web
  name: '@deepseek-ai/dsh-tool-web'
  config:
    fetch: false
    searchTimeoutMs: 60000
`;

const PRESET_META = `name: OpenSSH Remote Workspace\ndescription: Native OpenSSH-backed remote coding workspace provided by dsh-openssh-vpn.\n`;

export function ensureRemoteWorkspacePreset() {
  const root = presetRoot();
  mkdirSync(root, { recursive: true });
  const cordis = join(root, 'agent.cordis.yml');
  const meta = join(root, 'preset.yml');
  let changed = false;
  if (!existsSync(cordis) || readFileSync(cordis, 'utf8') !== PRESET_CORDIS) {
    writeFileSync(cordis, PRESET_CORDIS, 'utf8');
    changed = true;
  }
  if (!existsSync(meta) || readFileSync(meta, 'utf8') !== PRESET_META) {
    writeFileSync(meta, PRESET_META, 'utf8');
    changed = true;
  }
  return { id: REMOTE_PRESET_ID, path: cordis, changed };
}

function rpcRequest(payload) {
  return { rpcId: `openssh-vpn-${randomUUID()}`, payload };
}

function unwrap(method, response) {
  if (!response?.result?.ok) {
    const error = response?.result?.error;
    throw new Error(`${method} failed: ${error?.code || 'unknown'}: ${error?.message || 'unknown error'}`);
  }
  return response.result.value;
}

async function workspaceList(apiProxy) {
  return unwrap('workspace.list', await apiProxy.workspace.list(rpcRequest({})));
}

export async function listRemoteWorkspaces(ctx) {
  const apiProxy = ctx.get?.('apiProxy');
  const workspaceValue = apiProxy ? await workspaceList(apiProxy) : { items: [] };
  const byPath = new Map((workspaceValue.items || []).map((item) => [resolve(item.path), item]));
  const output = [];
  const root = remoteWorkspaceRoot();
  if (!existsSync(root)) return output;
  for (const aliasEntry of readdirSync(root, { withFileTypes: true })) {
    if (!aliasEntry.isDirectory()) continue;
    const aliasRoot = join(root, aliasEntry.name);
    for (const anchorEntry of readdirSync(aliasRoot, { withFileTypes: true })) {
      if (!anchorEntry.isDirectory()) continue;
      const anchor = join(aliasRoot, anchorEntry.name);
      const manifest = readRemoteWorkspaceManifest(anchor);
      if (!manifest) continue;
      const workspace = byPath.get(resolve(anchor));
      output.push({
        alias: manifest.alias,
        remotePath: manifest.remotePath,
        title: manifest.title,
        anchor: manifest.anchor,
        ...(workspace ? {
          workspaceId: workspace.workspaceId,
          sessionIds: workspace.sessionIds,
        } : {}),
      });
    }
  }
  return output;
}

export async function openRemoteWorkspace(ctx, engine, aliasInput, remotePathInput) {
  const alias = safeAlias(aliasInput);
  const remotePath = normalizeRemotePath(remotePathInput);
  const title = displayTitle(alias, remotePath);

  // Validate the remote directory through the exact same OpenSSH/runtime path
  // the eventual tools use. This also gives an actionable error before a
  // durable Harness workspace is registered.
  const probe = await engine.exec(
    alias,
    `test -d ${shellQuote(remotePath)} && printf DSH_REMOTE_WORKSPACE_OK`,
    30_000,
  );
  if (!probe.success || !probe.stdout.includes('DSH_REMOTE_WORKSPACE_OK')) {
    throw new Error(probe.stderr.trim() || probe.error || `remote directory is unavailable: ${alias}:${remotePath}`);
  }

  const anchor = anchorFor(alias, remotePath);
  writeRemoteWorkspaceManifest(anchor, {
    version: 1,
    alias,
    remotePath,
    title,
  });
  ensureRemoteWorkspacePreset();

  const apiProxy = ctx.get?.('apiProxy');
  if (!apiProxy?.workspace || !apiProxy?.sessions) {
    throw new Error('Harness apiProxy is unavailable; remote Workspace requires the Web profile host gateway');
  }

  const created = unwrap(
    'workspace.create',
    await apiProxy.workspace.create(rpcRequest({ path: anchor })),
  );
  let workspace = created.workspace;
  if (workspace.title !== title) {
    workspace = unwrap(
      'workspace.rename',
      await apiProxy.workspace.rename(rpcRequest({ workspaceId: workspace.workspaceId, title })),
    ).workspace;
  }

  // Reuse a blank remote-preset session when one already exists; otherwise
  // create a fresh session through the official gateway so persistence,
  // workspace attachment, model selection and preset composition stay native.
  let sessionId;
  const listed = await apiProxy.sessions.list(rpcRequest({}));
  if (listed?.result?.ok) {
    const candidates = listed.result.value.items || [];
    const attached = new Set(workspace.sessionIds || []);
    const blank = candidates.find((item) =>
      attached.has(item.sessionId)
      && item.blank === true
      && item.agentPreset === REMOTE_PRESET_ID);
    sessionId = blank?.sessionId;
  }

  if (!sessionId) {
    const session = unwrap(
      'session.create',
      await apiProxy.sessions.create(rpcRequest({
        workspaceId: workspace.workspaceId,
        agentPreset: REMOTE_PRESET_ID,
      })),
    );
    sessionId = session.sessionId;
  }

  return {
    ok: true,
    alias,
    remotePath,
    title,
    anchor,
    workspaceId: workspace.workspaceId,
    sessionId,
    agentPreset: REMOTE_PRESET_ID,
  };
}
